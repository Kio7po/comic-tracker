import { defineConfig } from 'vitest/config'
import react from '@vitejs/plugin-react'
import tailwindcss from '@tailwindcss/vite'
import { VitePWA } from 'vite-plugin-pwa'
import path from 'node:path'

// https://vite.dev/config/
export default defineConfig({
  plugins: [
    react(),
    tailwindcss(),
    VitePWA({
      // The plugin generates the service worker (Workbox) from this config, instead of
      // `injectManifest`, where we'd write our own worker file and the plugin would only inject the
      // precache list into it. No current needs for custom worker code; switch to `injectManifest`
      // if that changes (e.g. push notifications for new chapters).
      strategies: 'generateSW',
      // A new version doesn't take over by itself: the app is told one is waiting and the user
      // decides when to reload, so an open form isn't lost to a surprise refresh.
      registerType: 'prompt',
      // Already in public/ (generated by `pnpm generate-pwa-assets`), copied as-is; listing them
      // here also precaches them.
      includeAssets: ['favicon.ico', 'favicon.svg', 'apple-touch-icon-180x180.png'],
      manifest: {
        name: 'Manganamao',
        short_name: 'Manganamao',
        description:
          'Find where to read comics and manga online: a community-built catalog of reading sources, plus your own reading tracker.',
        start_url: '/',
        scope: '/',
        display: 'standalone',
        // A manifest holds a single value, so the light theme's --card (same hex as the light
        // data-light in index.html). The <meta name="theme-color"> there overrides it at runtime.
        theme_color: '#f7f8fc',
        // Android's navigation bar can't be drawn under by an installed PWA (safe-area-inset-bottom
        // is 0) and takes its color from here, a single static value that can't follow the
        // in-app theme. So a neutral dark grey (oklch(0.18 0.005 264), a step below the dark
        // theme's --background) that reads acceptably next to both themes. Omitting the key does
        // not help: the bar goes white, and the plugin would also fill in "#ffffff" by itself.
        // It's also the splash screen's background.
        background_color: '#101214',
        icons: [
          { src: 'pwa-64x64.png', sizes: '64x64', type: 'image/png' },
          { src: 'pwa-192x192.png', sizes: '192x192', type: 'image/png' },
          { src: 'pwa-512x512.png', sizes: '512x512', type: 'image/png' },
          { src: 'maskable-icon-512x512.png', sizes: '512x512', type: 'image/png', purpose: 'maskable' }
        ],
      },
      workbox: {
        // Only the app shell is precached. Everything the service worker answers for a
        // navigation falls back to index.html, so API calls and robots.txt must be excluded or
        // they'd get the app instead of their own response.
        navigateFallbackDenylist: [/^\/api\//, /^\/robots\.txt$/],
        cleanupOutdatedCaches: true,
      },
    }),
  ],
  resolve: {
    alias: {
      '@': path.resolve(__dirname, './src')
    }
  },
  server: {
    proxy: {
      '/api': {
        target: 'http://localhost:8080',
        changeOrigin: true,
      }
    }
  },
  test: {
    environment: 'jsdom',
    passWithNoTests: true,
    coverage: {
      provider: 'v8',
      reporter: ['text', 'lcov'],
    },
  },
})
